local Set = require("PZISCollectionUtils").Set

describe("PZISCollectionUtils.Set", function()
    local set

    before_each(function()
        set = Set:new({ "a", "b", "a" })
    end)

    describe("new", function()
        it("deduplicates the initial list", function()
            assert.are.equal(2, set:size())
            assert.is_true(set:contains("a"))
            assert.is_true(set:contains("b"))
        end)

        it("creates an empty set without a list", function()
            assert.are.equal(0, Set:new():size())
        end)
    end)

    describe("add", function()
        it("adds a new member and increases size", function()
            assert.are.equal(2, set:size())
            set:add("c")
            assert.is_true(set:contains("c"))
            assert.are.equal(3, set:size())
        end)

        it("keeps size unchanged for a duplicate", function()
            assert.are.equal(2, set:size())
            set:add("a")
            assert.is_true(set:contains("a"))
            assert.are.equal(2, set:size())
        end)
    end)

    describe("contains", function()
        it("finds a present member without changing size", function()
            assert.are.equal(2, set:size())
            assert.is_true(set:contains("a"))
            assert.are.equal(2, set:size())
        end)

        it("rejects an absent member without changing size", function()
            assert.are.equal(2, set:size())
            assert.is_false(set:contains("zebra"))
            assert.are.equal(2, set:size())
        end)

        it("also finds inherited method names without counting them", function()
            local empty = Set:new()
            assert.are.equal(0, empty:size())
            assert.is_true(empty:contains("add"))
            assert.are.equal(0, empty:size())
        end)
    end)

    describe("merge", function()
        it("unions overlapping sets without changing the source", function()
            local other = Set:new({ "b", "c" })
            assert.are.equal(2, set:size())
            assert.are.equal(2, other:size())

            set:merge(other)

            assert.are.equal(3, set:size())
            assert.is_true(set:contains("a"))
            assert.is_true(set:contains("b"))
            assert.is_true(set:contains("c"))
            assert.are.equal(2, other:size())
            assert.is_true(other:contains("b"))
            assert.is_true(other:contains("c"))
            assert.is_false(other:contains("a"))
        end)
    end)

    describe("size", function()
        it("tracks cardinality through successive additions and merges", function()
            assert.are.equal(2, set:size())
            set:add("c")
            assert.are.equal(3, set:size())
            set:add("c")
            assert.are.equal(3, set:size())
            local other = Set:new({ "c", "d" })
            assert.are.equal(2, other:size())
            set:merge(other)
            assert.are.equal(4, set:size())
            assert.are.equal(2, other:size())
        end)
    end)
end)
